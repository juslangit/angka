"""Run every reference query against public/data and write evals/coverage.md.

    uv run python evals/run_gold.py
"""

import json
from pathlib import Path

import duckdb

from gold import Q

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "public" / "data"


def main():
    con = duckdb.connect()
    tables = json.loads((DATA / "catalogue.json").read_text())["tables"]
    for t in tables:
        con.execute(f"CREATE VIEW {t['id']} AS SELECT * FROM read_parquet('{DATA / (t['id'] + '.parquet')}')")

    lines = [
        "# Coverage of the seed questions",
        "",
        "Generated by `evals/run_gold.py` from `evals/gold.py`. Every answerable question has a reference",
        "SQL query, run here against the built data. These results are the first gold answers for M3.",
        "",
    ]
    counts, failures, results = {}, [], {}
    for q in Q:
        counts[q["status"]] = counts.get(q["status"], 0) + 1
        if "sql" not in q:
            continue
        try:
            rel = con.execute(q["sql"])
            cols = [d[0] for d in rel.description]
            rows = rel.fetchall()
            if not rows or all(v is None for v in rows[0]):
                failures.append((q["id"], "empty result"))
            results[q["id"]] = (cols, rows)
        except Exception as e:  # noqa: BLE001 — report every broken query, keep going
            failures.append((q["id"], str(e).splitlines()[0]))

    lines.append("| Status | Count |")
    lines.append("|---|---|")
    for k in ("ok", "partial", "gap", "refuse"):
        lines.append(f"| {k} | {counts.get(k, 0)} |")
    lines += ["", f"Reference queries that failed or came back empty: {len(failures)}", ""]
    for i, err in failures:
        lines.append(f"- Q{i}: {err}")

    lines += ["", "## Answers", ""]
    for q in Q:
        lines.append(f"### Q{q['id']} · {q['lang']} · {q['status']}")
        lines.append(f"**{q['question']}**")
        if q.get("note"):
            lines.append(f"_{q['note']}_")
        if q["id"] in results:
            cols, rows = results[q["id"]]
            shown = rows[:12]
            lines.append("")
            lines.append("| " + " | ".join(cols) + " |")
            lines.append("|" + "---|" * len(cols))
            for r in shown:
                lines.append("| " + " | ".join(str(v) for v in r) + " |")
            if len(rows) > len(shown):
                lines.append(f"| … {len(rows) - len(shown)} more rows |" + " |" * (len(cols) - 1))
        lines.append("")

    (ROOT / "evals" / "coverage.md").write_text("\n".join(lines))
    print(counts, "failures:", failures)


if __name__ == "__main__":
    main()
