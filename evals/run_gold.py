"""Run every reference query against public/data and write evals/coverage.md.

    uv run python evals/run_gold.py
"""

import json
from pathlib import Path

import duckdb

from gold import Q as SEED
from gold_more import Q as MORE

Q = SEED + MORE


def split_of(q):
    """dev: the 50 seed questions (used to tune prompts) plus every third new one; test: the rest,
    held out — only its overall score is looked at, never its individual questions."""
    return "dev" if q["id"] <= 50 or q["id"] % 3 == 0 else "test"

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "public" / "data"


def main():
    con = duckdb.connect()
    tables = json.loads((DATA / "catalogue.json").read_text())["tables"]
    for t in tables:
        con.execute(f"CREATE VIEW {t['id']} AS SELECT * FROM read_parquet('{DATA / (t['id'] + '.parquet')}')")

    lines = [
        "# Coverage of the seed questions",
        "",
        "Generated by `evals/run_gold.py` from `evals/gold.py`. Every answerable question has a reference",
        "SQL query, run here against the built data. These results are the first gold answers for M3.",
        "",
    ]
    counts, failures, results = {}, [], {}
    for q in Q:
        counts[q["status"]] = counts.get(q["status"], 0) + 1
        if "sql" not in q:
            continue
        try:
            rel = con.execute(q["sql"])
            cols = [d[0] for d in rel.description]
            rows = rel.fetchall()
            if not rows or all(v is None for v in rows[0]):
                failures.append((q["id"], "empty result"))
            results[q["id"]] = (cols, rows)
        except Exception as e:  # noqa: BLE001 — report every broken query, keep going
            failures.append((q["id"], str(e).splitlines()[0]))

    lines.append("| Status | Count |")
    lines.append("|---|---|")
    for k in ("ok", "partial", "gap", "refuse"):
        lines.append(f"| {k} | {counts.get(k, 0)} |")
    lines += ["", f"Reference queries that failed or came back empty: {len(failures)}", ""]
    for i, err in failures:
        lines.append(f"- Q{i}: {err}")

    splits = {}
    for q in Q:
        sp = splits.setdefault(split_of(q), {"EN": 0, "BM": 0, "rojak": 0, "answer": 0, "refuse": 0})
        sp[q["lang"]] += 1
        sp["refuse" if q["status"] in ("gap", "refuse") else "answer"] += 1
    lines += ["", "## Dev / test split", "", "| Split | Questions | EN | BM | rojak | to answer | to refuse |", "|---|---|---|---|---|---|---|"]
    for name, sp in sorted(splits.items()):
        lines.append(f"| {name} | {sp['answer'] + sp['refuse']} | {sp['EN']} | {sp['BM']} | {sp['rojak']} | {sp['answer']} | {sp['refuse']} |")
    lines.append("")
    lines.append("The test answers are listed below like the rest, but only the test set's overall score is used: its individual results are never looked at while tuning.")

    lines += ["", "## Answers", ""]
    for q in Q:
        lines.append(f"### Q{q['id']} · {q['lang']} · {q['status']} · {split_of(q)}")
        lines.append(f"**{q['question']}**")
        if q.get("note"):
            lines.append(f"_{q['note']}_")
        if q["id"] in results:
            cols, rows = results[q["id"]]
            shown = rows[:12]
            lines.append("")
            lines.append("| " + " | ".join(cols) + " |")
            lines.append("|" + "---|" * len(cols))
            for r in shown:
                lines.append("| " + " | ".join(str(v) for v in r) + " |")
            if len(rows) > len(shown):
                lines.append(f"| … {len(rows) - len(shown)} more rows |" + " |" * (len(cols) - 1))
        lines.append("")

    (ROOT / "evals" / "coverage.md").write_text("\n".join(lines))

    # The same answers as data, for the model eval (evals/run_model.mjs)
    gold = []
    for q in Q:
        item = {k: q[k] for k in ("id", "question", "lang", "status")}
        item["split"] = split_of(q)
        item["note"] = q.get("note", "")
        for k in ("key", "match"):
            if q.get(k):
                item[k] = q[k]
        if q["id"] in results:
            cols, rows = results[q["id"]]
            item["columns"] = cols
            item["rows"] = [[v.isoformat() if hasattr(v, "isoformat") else v for v in r] for r in rows]
        gold.append(item)
    (ROOT / "evals" / "gold.json").write_text(json.dumps(gold, ensure_ascii=False, indent=1, default=str))
    print(counts, "failures:", failures)


if __name__ == "__main__":
    main()
